        <p>
            Sebelum berdirinya <strong>Dinas Kebudayaan Kota Ternate</strong>, urusan pemerintahan bidang kebudayaan berada dalam lingkup Dinas Pendidikan dan Kebudayaan. Seiring lahirnya <strong>Peraturan Pemerintah Nomor 18 Tahun 2016</strong> tentang Perangkat Daerah, Pemerintah Kota Ternate mengambil langkah strategis untuk memperkuat kelembagaan perlindungan warisan budaya.
        </p>
        <p>
            Kota Ternate memiliki keistimewaan tersendiri di kancah nasional dan internasional. Dikenal sebagai salah satu <strong>Kota Pusaka terkemuka di Indonesia</strong>, Ternate menyimpan ragam cagar budaya bernilai sejarah tinggi—mulai dari benteng-benteng peninggalan kolonial (Kalamata, Kastela, Tolukko, Oranje), kompleks Kedaton Kesultanan Ternate, makam para Sultan dan ulama, hingga memori kolektif sebagai episentrum awal perdagangan rempah dunia.
        </p>
        <p>
            Dengan diterbitkannya <strong>Peraturan Daerah Kota Ternate Nomor 19 Tahun 2018</strong> tentang Perubahan Kedua atas Peraturan Daerah Nomor 11 Tahun 2016 tentang Pembentukan dan Susunan Perangkat Daerah, maka resmi dibentuk <strong>Dinas Kebudayaan Kota Ternate</strong> sebagai Organisasi Perangkat Daerah (OPD) mandiri.
        </p>
    </div>

